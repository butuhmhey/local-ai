/** Return a full inline <svg> markup string for the named icon. */
export function svgIcon(name: string, size = 18): string {
  const body = PATHS[name];
  if (!body) throw new Error(`Unknown icon: ${name}`);
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

/** Return an <svg> element for the named icon (safe to pass to createElement children). */
export function iconEl(name: string, size = 18, className = ''): SVGSVGElement {
  const template = document.createElement('template');
  template.innerHTML = svgIcon(name, size).trim();
  const svg = template.content.firstElementChild as SVGSVGElement;
  if (className) svg.setAttribute('class', className);
  return svg;
}